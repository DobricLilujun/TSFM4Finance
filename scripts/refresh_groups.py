#!/usr/bin/env python3
"""Regenerate ``series_groups`` in bench/config.yaml from the datasets on disk.

The sweep iterates groups, so a dataset that is not in a group is invisible to every stage.
After any download, run this: it keeps the hand-curated groups (core12/long12/newx) and
rebuilds the data-driven ones from meta.json (domain / frequency / naming).
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CFG = REPO / "tsfm4finance" / "bench" / "config.yaml"
OPEN = REPO / "data" / "open"

KEEP = ("core12", "long12", "newx")          # hand-curated, never rewritten


def members(pred) -> list[str]:
    out = []
    for p in sorted(OPEN.iterdir()):
        m = p / "meta.json"
        if not m.exists():
            continue
        d = json.loads(m.read_text())
        if any(d["name"].endswith(t) for t in ("_dir5", "_volreg", "_extreme", "_trade")):
            continue
        if pred(d):
            out.append(d["name"])
    return out


def build() -> dict[str, list[str]]:
    g: dict[str, list[str]] = {}
    g["crypto_spot"] = members(lambda d: d["name"].startswith("cx_") and d["name"].endswith("_1d"))
    g["crypto_1h"] = members(lambda d: d["name"].startswith("cx_") and d["name"].endswith("_1h"))
    g["crypto_fresh"] = members(lambda d: d["name"].startswith("cx_") and d["name"].endswith("_fresh"))
    g["crypto_deriv"] = members(lambda d: d["name"].startswith(("cd_", "cf_")))
    g["crypto_pegs"] = members(lambda d: d["name"].startswith("peg_"))
    g["crypto_all"] = sorted(set(g["crypto_spot"]) | set(g["crypto_1h"]) |
                             set(g["crypto_deriv"]) | set(g["crypto_pegs"]))
    g["fred"] = [p.name for p in sorted(OPEN.iterdir()) if p.name.startswith("fred_")]
    g["intraday"] = sorted(set(g["crypto_1h"]) | set(g["crypto_fresh"]))
    g["crypto_clean"] = sorted({d["name"] for d in
                                (json.loads((p / "meta.json").read_text())
                                 for p in OPEN.iterdir() if (p / "meta.json").exists())
                                if d.get("contamination") in ("fresh", "post_listing", "rare")
                                and not any(d["name"].endswith(t)
                                            for t in ("_dir5", "_volreg", "_extreme", "_trade"))})
    return {k: v for k, v in g.items() if v}


def parse_block(block: str) -> dict[str, list[str]]:
    """Parse a ``  name: [a, b,\n  c]`` block into {name: [members]}."""
    out: dict[str, list[str]] = {}
    cur = None
    for line in block.splitlines():
        if not line.strip():
            continue
        m = re.match(r"^  ([A-Za-z_][\w]*):\s*(.*)$", line)
        if m:
            cur = m.group(1)
            out[cur] = []
            rest = m.group(2).strip()
        else:
            rest = line.strip()
        if cur is None:
            continue
        rest = rest.strip("[]").strip()
        while rest.startswith("- "):                 # block-sequence style members
            rest = rest[2:].strip()
        if rest:
            out[cur] += [x.strip() for x in rest.split(",") if x.strip()]
    return out


def main() -> None:
    """Replace the ``series_groups:`` block, keeping the rest of the file verbatim."""
    import yaml
    lines = CFG.read_text().splitlines()
    try:
        start = next(i for i, l in enumerate(lines) if l.startswith("series_groups:"))
    except StopIteration:
        sys.exit("no series_groups: block in config.yaml")
    end = next((i for i in range(start + 1, len(lines)) if re.match(r"^[A-Za-z_]", lines[i])),
               len(lines))
    old = yaml.safe_load("\n".join(lines[start:end]))["series_groups"]
    groups = {k: [n.strip().strip("[]").strip() for n in
                  re.split(r"[,\n]", " ".join(v if isinstance(v, list) else [v]))
                  if n.strip().strip("[]").strip()]
              for k, v in old.items()}          # yaml already resolved flow vs block lists
    groups = {k: [str(n) for n in v] for k, v in old.items()}
    groups.update(build())
    for k, v in list(groups.items()):            # a missing member breaks every stage
        have = [n for n in v if (OPEN / n / "meta.json").exists()]
        if len(have) != len(v):
            print(f"  pruned {k}: {len(v) - len(have)} not on disk "
                  f"({', '.join(sorted(set(v) - set(have))[:3])}...)")
        groups[k] = have
    groups = {k: v for k, v in groups.items() if v}
    out = ["series_groups:",
           "  # data-driven groups are regenerated by scripts/refresh_groups.py after any",
           "  # download; core12 / long12 / newx stay hand-curated"]
    order = [k for k in ("core12", "long12", "newx", "fred", "external", "intraday")
             if k in groups] + sorted(k for k in groups if k not in
                                      ("core12", "long12", "newx", "fred", "external", "intraday"))
    for k in order:
        out.append(f"  {k}:")
        out += [f"  - {n}" for n in groups[k]]
    new_lines = lines[:start] + out + lines[end:]
    chk = yaml.safe_load("\n".join(new_lines))
    assert chk.get("series_groups") and chk.get("models"), "config would not load"
    CFG.write_text("\n".join(new_lines) + "\n")
    print("\n".join(f"  {k:<13} {len(v)}" for k, v in chk["series_groups"].items()))


if __name__ == "__main__":
    main()
