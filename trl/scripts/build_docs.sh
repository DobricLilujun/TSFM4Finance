#!/usr/bin/env bash
# Render the documentation site (GitHub Pages uses this same script).
#
# docs/matrix.md is generated from COMPATIBILITY.md, which `tsfm-trl doctor --merge`
# writes from reports/compat_matrix.json. The published table therefore cannot drift
# away from the data it came from — there is no hand-maintained copy to forget to update.
set -euo pipefail
cd "$(dirname "$0")/.."

PY="${DOCS_PY:-.venv-docs/bin/python}"
# An unset VIRTUAL_ENV used to make this "/bin/python" (the empty string plus a suffix),
# which exists on GitHub runners but has no mkdocs: the CI build died with
# `/bin/python: No module named mkdocs` while pip had installed into the setup-python
# interpreter. Only take the venv path when a venv is actually set.
if [ ! -x "$PY" ] && [ -n "${VIRTUAL_ENV:-}" ]; then PY="$VIRTUAL_ENV/bin/python"; fi
[ -x "$PY" ] || PY=python3

if [ ! -f COMPATIBILITY.md ]; then
  echo "COMPATIBILITY.md missing: run  tsfm-trl doctor --merge reports/*.json --md COMPATIBILITY.md" >&2
  exit 1
fi
{
  echo "<!-- generated by scripts/build_docs.sh from COMPATIBILITY.md / reports/compat_matrix.json; do not edit -->"
  echo
  cat COMPATIBILITY.md
} > docs/matrix.md

if [ -f EFFECTIVENESS.md ]; then
  {
    echo "<!-- generated by scripts/build_docs.sh from reports/effectiveness*.jsonl via scripts/sweep_evaluate.py; do not edit -->"
    echo
    cat EFFECTIVENESS.md
  } > docs/effectiveness.md
else
  rm -f docs/effectiveness.md
fi

# mkdocs.yml sets strict: true, so a broken nav entry or a link to a page that does not
# exist fails the build instead of publishing a half-site.
if [ "${1:-}" = "serve" ]; then
  exec "$PY" -m mkdocs serve
fi
exec "$PY" -m mkdocs build --strict
